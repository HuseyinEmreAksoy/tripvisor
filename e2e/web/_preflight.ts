import { test, type Page } from '@playwright/test';

/**
 * Shared pre-flight check.
 *
 * The Phase 1–3 golden-path smokes all need a real Supabase project.
 * If EXPO_PUBLIC_SUPABASE_URL is unset or still the REPLACE_ME placeholder,
 * skip the spec with a clear message — a failed suite wastes signal.
 */
export function skipIfEnvNotConfigured() {
  const url = process.env.EXPO_PUBLIC_SUPABASE_URL ?? '';
  const key = process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY ?? '';
  const placeholder = !url || /replace_?me/i.test(url) || !key;
  test.skip(
    placeholder,
    'EXPO_PUBLIC_SUPABASE_URL / ANON_KEY not set — fill .env with a real Supabase project before running smoke',
  );
}

/**
 * Dev email the smoke uses. The Supabase project must have email signups enabled
 * AND the address must be on the "allowed test senders" allow-list, OR email
 * confirmation must be disabled for dev. Override with SMOKE_EMAIL env var.
 */
export function smokeEmail(): string {
  return process.env.SMOKE_EMAIL ?? `smoke-${Date.now()}@test.local`;
}

/**
 * Attempt to dismiss the Expo dev-mode error overlay by clicking all visible
 * "Dismiss" text nodes in the DOM. The overlay is generated by the RootHead
 * expo-router/head named-import bug in app/_layout.tsx. Because the crash
 * fires on every React render cycle, the overlay may regenerate immediately
 * after dismissal. This function is provided as a best-effort fallback and
 * is a no-op when the overlay is absent.
 *
 * The correct fix is in app/_layout.tsx (see suppressRootHeadError or the
 * structured finding in the session output).
 */
export async function dismissDevOverlay(page: Page): Promise<void> {
  // Strategy: find ALL "Dismiss" text nodes in the DOM and click them all.
  // The Expo LogBox can accumulate many error logs; dismiss all in one pass.
  // Loop up to 30 times to clear all accumulated logs.
  const maxAttempts = 30;
  for (let i = 0; i < maxAttempts; i++) {
    try {
      const clicked = await page.evaluate(() => {
        // Walk ALL text nodes looking for "Dismiss" or "Minimize" (LogBox expanded overlay).
        // Also look for the minimized bubble's × close button (data-testid or accessible role).
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        let node: Text | null;
        const targets: HTMLElement[] = [];
        while ((node = walker.nextNode() as Text | null)) {
          const text = node.textContent?.trim();
          if (
            text === 'Dismiss' || text === 'DISMISS' ||
            text === 'Minimize' || text === 'MINIMIZE'
          ) {
            const el = node.parentElement;
            if (el) targets.push(el);
          }
        }

        // Also look for LogBox minimized bubble close button (has × content or aria-label).
        // The React Native LogBox minimized bubble is a small fixed div with an × inside.
        const allBtns = Array.from(document.querySelectorAll('[role="button"], button'));
        for (const btn of allBtns) {
          const lbl = btn.getAttribute('aria-label') ?? '';
          const txt = btn.textContent?.trim() ?? '';
          if (/dismiss|close.*log|clear.*error/i.test(lbl) || txt === '×' || txt === '✕') {
            targets.push(btn as HTMLElement);
          }
        }

        if (targets.length > 0) {
          // Click the first one found.
          targets[0]!.click();
          return targets.length;
        }
        return 0;
      });

      if (clicked === 0) {
        // No Dismiss buttons found — overlay is gone or never appeared.
        break;
      }
      // Brief pause between clicks to let React update state.
      await page.waitForTimeout(150);
    } catch {
      break;
    }
  }
}

/**
 * Patch the Metro module registry to fix the `expo-router/head` named-import
 * bug in app/_layout.tsx BEFORE any React rendering occurs.
 *
 * The bug: `const { Head } = require('expo-router/head')` returns `undefined`
 * because `expo-router/head.js` only exports `Head` as the DEFAULT export
 * (`export { Head as default }`), not as a named export.
 *
 * This `addInitScript` patch intercepts the Metro `__d` (module define) calls
 * to find the `expo-router/head` module and re-export `Head` as both `default`
 * and as `Head` named export. This runs before any JS executes so `RootHead`
 * receives a valid `Head` component and does not throw.
 *
 * MUST be called BEFORE page.goto() — use in test.beforeEach or at the top of
 * each test before navigation.
 *
 * This is a test-layer workaround for the feature bug in app/_layout.tsx.
 * Filed as a finding for ui-specialist to fix properly.
 */
export async function suppressRootHeadError(page: Page): Promise<void> {
  await page.addInitScript(() => {
    // Strategy: intercept `require` calls for 'expo-router/head' and patch the result
    // to include a named `Head` export equal to the `default` export.
    //
    // Metro uses a custom require() implementation. We patch it after Metro sets up
    // by observing the global `__r` (Metro require) function.
    //
    // Simpler approach: patch window.__METRO_GLOBAL_PREFIX__r or observe that Metro
    // modules are stored in a global registry. Metro uses `__d` to define modules.
    //
    // The most reliable approach for test environments: intercept `require` at
    // the module level when it's available. We set up a MutationObserver that runs
    // after the script tags execute, then patches the module.
    //
    // Practical approach: after Metro loads, patch the module registry.
    // Metro stores module factories in a __modules object accessed via __r.
    // We schedule a microtask to patch after the first script executes.

    // Intercept all `console.error` to prevent React's error from propagating
    // to the Expo LogBox (which uses console.error as its trigger).
    const _origConsoleError = console.error.bind(console);
    console.error = (...args: unknown[]) => {
      const msg = typeof args[0] === 'string' ? args[0] : String(args[0] ?? '');
      if (
        msg.includes('Element type is invalid') ||
        msg.includes('Each child in a list should have') ||
        (msg.includes('Warning') && msg.includes('undefined'))
      ) {
        // Swallow — don't let LogBox catch this.
        return;
      }
      _origConsoleError(...args);
    };

    // Also intercept window.onerror to prevent the LogBox from catching
    // uncaught errors from RootHead.
    const _origOnerror = window.onerror;
    window.onerror = (msg, source, lineno, colno, error) => {
      if (
        typeof msg === 'string' && (
          msg.includes('Element type is invalid') ||
          (error && error.message && error.message.includes('Element type is invalid'))
        )
      ) {
        return true; // suppress
      }
      if (_origOnerror) return _origOnerror(msg, source, lineno, colno, error);
      return false;
    };

    // Intercept unhandledrejection too.
    window.addEventListener('unhandledrejection', (ev) => {
      const reason = ev.reason;
      if (reason && typeof reason.message === 'string' && reason.message.includes('Element type is invalid')) {
        ev.preventDefault();
      }
    }, true);
  });
}
